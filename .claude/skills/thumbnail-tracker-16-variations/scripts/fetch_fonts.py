#!/usr/bin/env python3
"""Download the renderer's fonts into assets/fonts/ so render.cjs works offline.

Usage: python3 scripts/fetch_fonts.py [--subsets latin,latin-ext]

Fetches the same woff2 files Google Fonts serves to Chrome (so local renders match
the old Google-hosted renders pixel for pixel), each family's licence from
github.com/google/fonts, and writes assets/fonts/fonts.json, which render.cjs reads
to emit local @font-face rules. Stdlib only.
"""
import argparse
import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / "assets" / "fonts"

# family -> (css2 axis spec, licence path in github.com/google/fonts, licence name)
FAMILIES = {
    "Inter Tight": ("wght@700;800;900", "ofl/intertight/OFL.txt", "OFL-1.1"),
    "Permanent Marker": ("", "apache/permanentmarker/LICENSE.txt", "Apache-2.0"),
    "JetBrains Mono": ("wght@500;700", "ofl/jetbrainsmono/OFL.txt", "OFL-1.1"),
    "Caveat": ("wght@600;700", "ofl/caveat/OFL.txt", "OFL-1.1"),
    "Anton": ("", "ofl/anton/OFL.txt", "OFL-1.1"),
    "Fraunces": ("ital,wght@0,600;0,700;1,600", "ofl/fraunces/OFL.txt", "OFL-1.1"),
    "IBM Plex Mono": ("wght@500;600", "ofl/ibmplexmono/OFL.txt", "OFL-1.1"),
    "Instrument Sans": ("wght@400;500;600", "ofl/instrumentsans/OFL.txt", "OFL-1.1"),
}
UA = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36"
GH = "https://raw.githubusercontent.com/google/fonts/main/"


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--subsets", default="latin,latin-ext")
    a = ap.parse_args()
    subsets = a.subsets.split(",")
    FONTS.mkdir(parents=True, exist_ok=True)
    faces, files = [], {}
    for fam, (axes, lic, licname) in FAMILIES.items():
        q = fam.replace(" ", "+") + (":" + axes if axes else "")
        css = get(f"https://fonts.googleapis.com/css2?family={q}&display=block").decode()
        for m in re.finditer(r"/\* (\S+) \*/\s*@font-face \{(.*?)\}", css, re.S):
            sub, body = m.groups()
            if sub not in subsets:
                continue
            style = re.search(r"font-style: (\w+)", body).group(1)
            weight = int(re.search(r"font-weight: (\d+)", body).group(1))
            url = re.search(r"url\((https://[^)]+)\)", body).group(1)
            ur = re.search(r"unicode-range: ([^;]+);", body).group(1)
            name = f"{slug(fam)}{'-italic' if style == 'italic' else ''}-{sub}.woff2"
            if name not in files:
                data = get(url)
                (FONTS / name).write_bytes(data)
                files[name] = {"file": name, "family": fam, "style": style, "subset": sub,
                               "source": url, "bytes": len(data), "licence": licname,
                               "licence_file": f"LICENSE-{slug(fam)}.txt", "weights": []}
                print(f"{name}: {len(data)} bytes", file=sys.stderr)
            files[name]["weights"].append(weight)
            faces.append({"family": fam, "style": style, "weight": weight, "file": name,
                          "unicode_range": ur})
        (FONTS / f"LICENSE-{slug(fam)}.txt").write_bytes(get(GH + lic))
    manifest = {"note": "Generated by scripts/fetch_fonts.py. render.cjs reads 'faces'.",
                "google_css": "https://fonts.googleapis.com/css2",
                "licence_source": "https://github.com/google/fonts",
                "files": list(files.values()), "faces": faces}
    (FONTS / "fonts.json").write_text(json.dumps(manifest, indent=1) + "\n")
    print(json.dumps({"files": len(files), "faces": len(faces)}))


if __name__ == "__main__":
    main()
